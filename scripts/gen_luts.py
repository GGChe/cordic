#!/usr/bin/env python3
"""
Generate the hard-coded master tables of src/atan_lut.v and src/atanh_lut.v.

Each LUT stores one high-precision master table (unsigned 64-bit, MASTER_FRAC
fractional bits). The RTL derives the PHASE_WIDTH-bit entries from it with a
round-to-nearest right shift, so no real-valued math is needed at elaboration:

    atan_master[j]  = round( atan(2^-j) / pi * 2^MASTER_FRAC ),   j = 0 .. N_MASTER-1
    atanh_master[j] = round( atanh(2^-j)      * 2^MASTER_FRAC ),  j = 1 .. N_MASTER

Values are computed with exact series in 100-digit decimal arithmetic.

The script also verifies that "round the master value to W bits" gives exactly
the same result as rounding the true value to W bits (no double-rounding
error) for every entry and every PHASE_WIDTH from 4 to MAX_PHASE_WIDTH.

Usage:
    python3 scripts/gen_luts.py           # print the generated Verilog
    python3 scripts/gen_luts.py --write   # update the LUT files in place
    python3 scripts/gen_luts.py --check   # exit 1 if the files are out of date
"""

import argparse
import re
import sys
from decimal import ROUND_FLOOR, Decimal, getcontext
from pathlib import Path

getcontext().prec = 100

MASTER_FRAC = 62   # fractional bits of the master tables (must match the RTL)
N_MASTER = 40      # entries per master table (must match the RTL)
MAX_PHASE_WIDTH = 48  # widest PHASE_WIDTH the RTL accepts (must match the RTL)

ROOT = Path(__file__).resolve().parent.parent
BEGIN = "// BEGIN GENERATED by scripts/gen_luts.py — do not edit by hand"
END = "// END GENERATED"


def atan_series(x):
    """atan(x) for |x| <= 1/2 (Taylor series)."""
    term, total, k = x, Decimal(0), 0
    eps = Decimal(10) ** -(getcontext().prec - 5)
    while abs(term) > eps:
        total += term / (2 * k + 1)
        term *= -x * x
        k += 1
    return total


def atanh_series(x):
    """atanh(x) for |x| <= 1/2 (Taylor series)."""
    term, total, k = x, Decimal(0), 0
    eps = Decimal(10) ** -(getcontext().prec - 5)
    while abs(term) > eps:
        total += term / (2 * k + 1)
        term *= x * x
        k += 1
    return total


PI = 16 * atan_series(Decimal(1) / 5) - 4 * atan_series(Decimal(1) / 239)  # Machin


def atan_over_pi(j):
    if j == 0:
        return Decimal(1) / 4                      # atan(1) = pi/4
    return atan_series(Decimal(2) ** -j) / PI


def atanh_exact(j):
    return atanh_series(Decimal(2) ** -j)


def round_scaled(value, frac_bits):
    """round-half-up(value · 2^frac_bits) as an int."""
    return int((value * (Decimal(2) ** frac_bits) + Decimal("0.5")).to_integral_value(ROUND_FLOOR))


def derive(master, frac_bits):
    """What the RTL computes: (master + 2^(s-1)) >> s, s = MASTER_FRAC - frac_bits."""
    s = MASTER_FRAC - frac_bits
    return (master + (1 << (s - 1))) >> s


def tables():
    atan = [(j, atan_over_pi(j)) for j in range(N_MASTER)]
    atanh = [(j, atanh_exact(j)) for j in range(1, N_MASTER + 1)]
    return atan, atanh


def verify(entries, frac_offset, name):
    """frac_offset: PHASE_WIDTH − frac_bits (1 for atan, 2 for atanh)."""
    bad = []
    for j, v in entries:
        master = round_scaled(v, MASTER_FRAC)
        for width in range(4, MAX_PHASE_WIDTH + 1):
            frac = width - frac_offset
            if derive(master, frac) != round_scaled(v, frac):
                bad.append((j, width))
    if bad:
        print(f"{name}: double-rounding mismatches at (j, PHASE_WIDTH): {bad[:10]}", file=sys.stderr)
    return not bad


def verilog_function(fname, entries, comment):
    lines = [
        BEGIN,
        f"  // {comment}",
        f"  function [63:0] {fname};",
        "    input integer j;",
        "    begin",
        f"      case (j)",
    ]
    for j, v in entries:
        m = round_scaled(v, MASTER_FRAC)
        h = f"{m:016x}"
        lines.append(f"        {j:2d}: {fname} = 64'h{h[0:4]}_{h[4:8]}_{h[8:12]}_{h[12:16]};")
    lines += [
        f"        default: {fname} = 64'd0;",
        "      endcase",
        "    end",
        "  endfunction",
        f"  {END}",
    ]
    return "\n".join("  " + l if not l.startswith("  ") else l for l in lines)


def render():
    atan, atanh = tables()
    ok = verify(atan, 1, "atan") & verify(atanh, 2, "atanh")
    return ok, {
        ROOT / "src" / "atan_lut.v": verilog_function(
            "atan_master", atan,
            f"atan(2^-j) / pi * 2^{MASTER_FRAC},  j = 0 .. {N_MASTER - 1}"),
        ROOT / "src" / "atanh_lut.v": verilog_function(
            "atanh_master", atanh,
            f"atanh(2^-j) * 2^{MASTER_FRAC},  j = 1 .. {N_MASTER}"),
    }


def splice(text, block):
    pattern = re.compile(r"[ \t]*" + re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if not pattern.search(text):
        raise SystemExit("generated-block markers not found")
    return pattern.sub(lambda _: block, text, count=1)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", action="store_true", help="update the LUT files in place")
    ap.add_argument("--check", action="store_true", help="fail if the LUT files are out of date")
    args = ap.parse_args()

    ok, blocks = render()
    if not ok:
        return 1

    stale = False
    for path, block in blocks.items():
        if args.write or args.check:
            text = path.read_text()
            new = splice(text, block)
            if new != text:
                stale = True
                if args.write:
                    path.write_text(new)
                    print(f"updated {path.relative_to(ROOT)}")
                else:
                    print(f"{path.relative_to(ROOT)} is out of date", file=sys.stderr)
        else:
            print(f"// ---- {path.relative_to(ROOT)} ----\n{block}\n")

    if args.check and stale:
        return 1
    if args.check:
        print("LUT tables up to date; master → PHASE_WIDTH rounding verified exact")
    return 0


if __name__ == "__main__":
    sys.exit(main())
