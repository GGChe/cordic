// Combinational ROM containing pre-computed elementary angles for CORDIC.
//
//   atan_lut[j] = round( atan(2^-j) * 2^(PHASE_WIDTH-1) / pi ),  j = 0 .. N_ENTRIES-1
//
// For circular CORDIC (rotation/vectoring), these are atan(2^-j).
// The values are scaled so that pi maps to 2^(PHASE_WIDTH-1).
//
// Implementation:
//   The angles are hard-coded once, as a 64-bit master table with
//   MASTER_FRAC = 62 fractional bits (atan_master, generated by
//   scripts/gen_luts.py). Each PHASE_WIDTH-bit entry is that master value
//   rounded to nearest by a constant right shift — integer arithmetic only,
//   no real-valued math at elaboration. gen_luts.py verifies that this gives
//   exactly round(atan(2^-j)/pi · 2^(PHASE_WIDTH-1)) for every entry and every
//   PHASE_WIDTH up to 48. Addresses at or beyond N_ENTRIES read as zero.
//
// Parameters:
//   PHASE_WIDTH  — bit-width of the LUT entries (default 18, max 48)
//   N_ENTRIES    — number of LUT entries = number of CORDIC iterations (max 40)
//   ADDR_WIDTH   — address bus width, must satisfy 2^ADDR_WIDTH >= N_ENTRIES
//
// Default table (PHASE_WIDTH = 18, pi = 2^17 = 131072):
//
//   j |  atan(2^-j) (deg)  |  Fixed-point value
// ----+--------------------+---------------------
//   0 |   45.0000          |  32768
//   1 |   26.5651          |  19344
//   2 |   14.0362          |  10221
//   3 |    7.1250          |   5188
//   4 |    3.5763          |   2604
//   5 |    1.7899          |   1303
//   6 |    0.8952          |    652
//   7 |    0.4476          |    326
//   8 |    0.2238          |    163
//   9 |    0.1119          |     81
//  10 |    0.0560          |     41
//  11 |    0.0280          |     20
//  12 |    0.0140          |     10
//  13 |    0.0070          |      5
//  14 |    0.0035          |      3
//  15 |    0.0017          |      1
// =============================================================================

`timescale 1ns / 1ps

module atan_lut #(
  parameter PHASE_WIDTH = 18,
  parameter N_ENTRIES   = 16,
  parameter ADDR_WIDTH  = 4
)(
  input  [ADDR_WIDTH-1:0]         address,
  output signed [PHASE_WIDTH-1:0] data
);

  // Master table format (must match scripts/gen_luts.py)
  localparam MASTER_FRAC     = 62;
  localparam N_MASTER        = 40;
  localparam MAX_PHASE_WIDTH = 48;

  // Right shift from the master scale (2^62 = pi) to PHASE_WIDTH (2^(W-1) = pi)
  localparam SHIFT = MASTER_FRAC - (PHASE_WIDTH - 1);

  // ── Elaboration-time parameter checks ──
  // Instantiating an undefined module is the portable way (Icarus, Verilator,
  // Yosys) to abort elaboration on an invalid parameter combination.
  generate
    if (N_ENTRIES > (1 << ADDR_WIDTH)) begin : g_check_addr
      ERROR_atan_lut_N_ENTRIES_exceeds_ADDR_WIDTH u_param_error ();
    end
    if (N_ENTRIES > N_MASTER) begin : g_check_entries
      ERROR_atan_lut_N_ENTRIES_must_be_at_most_40 u_param_error ();
    end
    if (PHASE_WIDTH > MAX_PHASE_WIDTH) begin : g_check_width
      ERROR_atan_lut_PHASE_WIDTH_must_be_at_most_48 u_param_error ();
    end
  endgenerate

  // BEGIN GENERATED by scripts/gen_luts.py — do not edit by hand
  // atan(2^-j) / pi * 2^62,  j = 0 .. 39
  function [63:0] atan_master;
    input integer j;
    begin
      case (j)
         0: atan_master = 64'h1000_0000_0000_0000;
         1: atan_master = 64'h0972_028e_cef9_8433;
         2: atan_master = 64'h04fd_9c2d_af71_cf47;
         3: atan_master = 64'h0288_88ea_0eee_cd0e;
         4: atan_master = 64'h0145_86a1_872c_4d76;
         5: atan_master = 64'h00a2_ebf0_ac82_313c;
         6: atan_master = 64'h0051_7b0f_2e14_1315;
         7: atan_master = 64'h0028_be2a_88ea_2157;
         8: atan_master = 64'h0014_5f29_a368_619b;
         9: atan_master = 64'h000a_2f97_5d98_559c;
        10: atan_master = 64'h0005_17cc_0048_dd3e;
        11: atan_master = 64'h0002_8be6_0a54_065c;
        12: atan_master = 64'h0001_45f3_066f_f631;
        13: atan_master = 64'h0000_a2f9_8360_b979;
        14: atan_master = 64'h0000_517c_c1b5_7489;
        15: atan_master = 64'h0000_28be_60db_5d3e;
        16: atan_master = 64'h0000_145f_306d_c2fe;
        17: atan_master = 64'h0000_0a2f_9836_e40b;
        18: atan_master = 64'h0000_0517_cc1b_7257;
        19: atan_master = 64'h0000_028b_e60d_b936;
        20: atan_master = 64'h0000_0145_f306_dc9c;
        21: atan_master = 64'h0000_00a2_f983_6e4e;
        22: atan_master = 64'h0000_0051_7cc1_b727;
        23: atan_master = 64'h0000_0028_be60_db94;
        24: atan_master = 64'h0000_0014_5f30_6dca;
        25: atan_master = 64'h0000_000a_2f98_36e5;
        26: atan_master = 64'h0000_0005_17cc_1b72;
        27: atan_master = 64'h0000_0002_8be6_0db9;
        28: atan_master = 64'h0000_0001_45f3_06dd;
        29: atan_master = 64'h0000_0000_a2f9_836e;
        30: atan_master = 64'h0000_0000_517c_c1b7;
        31: atan_master = 64'h0000_0000_28be_60dc;
        32: atan_master = 64'h0000_0000_145f_306e;
        33: atan_master = 64'h0000_0000_0a2f_9837;
        34: atan_master = 64'h0000_0000_0517_cc1b;
        35: atan_master = 64'h0000_0000_028b_e60e;
        36: atan_master = 64'h0000_0000_0145_f307;
        37: atan_master = 64'h0000_0000_00a2_f983;
        38: atan_master = 64'h0000_0000_0051_7cc2;
        39: atan_master = 64'h0000_0000_0028_be61;
        default: atan_master = 64'd0;
      endcase
    end
  endfunction
  // END GENERATED

  // ── ROM contents: master table rounded to PHASE_WIDTH bits ──
  // Sized to the full address space; entries at or beyond N_ENTRIES are zero.
  localparam DEPTH = 1 << ADDR_WIDTH;

  wire signed [PHASE_WIDTH-1:0] lut [0:DEPTH-1];

  genvar j;
  generate
    for (j = 0; j < DEPTH; j = j + 1) begin : g_rom
      if (j < N_ENTRIES) begin : g_entry
        localparam [63:0] MASTER = atan_master(j);
        localparam [63:0] VALUE  = (MASTER + (64'd1 << (SHIFT - 1))) >> SHIFT;
        assign lut[j] = VALUE[PHASE_WIDTH-1:0];
      end else begin : g_zero
        assign lut[j] = {PHASE_WIDTH{1'b0}};
      end
    end
  endgenerate

  // Combinational read — no clock needed, purely addressed ROM
  assign data = lut[address];

endmodule
