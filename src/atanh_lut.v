// data = round(atanh(2^−(address+1)) · 2^(PHASE_WIDTH−2)), i.e. Q2.(PHASE_WIDTH−2)
// (the square-root core reaches |z| ≈ 1.06); 0 for address >= N_ENTRIES.
// It starts at j = 1 because atanh(1) = ∞.
//
// Same master-table scheme and limits as atan_lut (see atan_lut.v).
//
// Default table (PHASE_WIDTH = 18): 35999, 16739, 8235, 4101, 2049, 1024,
// 512, 256, 128, 64, 32, 16, 8, 4.
// =============================================================================

`timescale 1ns / 1ps

module atanh_lut #(
  parameter PHASE_WIDTH = 18,
  parameter N_ENTRIES   = 14,
  parameter ADDR_WIDTH  = 4
)(
  input  [ADDR_WIDTH-1:0]             address,
  output signed [PHASE_WIDTH-1:0]     data
);

  // Must match scripts/gen_luts.py
  localparam MASTER_FRAC     = 62;
  localparam N_MASTER        = 40;
  localparam MAX_PHASE_WIDTH = 48;

  localparam SHIFT = MASTER_FRAC - (PHASE_WIDTH - 2);

  // Invalid parameters abort elaboration (undefined module)
  generate
    if (N_ENTRIES > (1 << ADDR_WIDTH)) begin : g_check_addr
      ERROR_atanh_lut_N_ENTRIES_exceeds_ADDR_WIDTH u_param_error ();
    end
    if (N_ENTRIES > N_MASTER) begin : g_check_entries
      ERROR_atanh_lut_N_ENTRIES_must_be_at_most_40 u_param_error ();
    end
    if (PHASE_WIDTH > MAX_PHASE_WIDTH) begin : g_check_width
      ERROR_atanh_lut_PHASE_WIDTH_must_be_at_most_48 u_param_error ();
    end
  endgenerate

  // BEGIN GENERATED by scripts/gen_luts.py — do not edit by hand
  // atanh(2^-j) * 2^62,  j = 1 .. 40
  function [63:0] atanh_master;
    input integer j;
    begin
      case (j)
         1: atanh_master = 64'h2327_d4f5_5a06_152f;
         2: atanh_master = 64'h1058_aefa_8114_51a7;
         3: atanh_master = 64'h080a_c48e_4f57_7bb5;
         4: atanh_master = 64'h0401_5622_b4dd_6b37;
         5: atanh_master = 64'h0200_2ab1_1235_dc49;
         6: atanh_master = 64'h0100_0555_888a_d1ca;
         7: atanh_master = 64'h0080_00aa_ac44_48d7;
         8: atanh_master = 64'h0040_0015_5562_222b;
         9: atanh_master = 64'h0020_0002_aaab_1111;
        10: atanh_master = 64'h0010_0000_5555_5889;
        11: atanh_master = 64'h0008_0000_0aaa_aac4;
        12: atanh_master = 64'h0004_0000_0155_5556;
        13: atanh_master = 64'h0002_0000_002a_aaab;
        14: atanh_master = 64'h0001_0000_0005_5555;
        15: atanh_master = 64'h0000_8000_0000_aaab;
        16: atanh_master = 64'h0000_4000_0000_1555;
        17: atanh_master = 64'h0000_2000_0000_02ab;
        18: atanh_master = 64'h0000_1000_0000_0055;
        19: atanh_master = 64'h0000_0800_0000_000b;
        20: atanh_master = 64'h0000_0400_0000_0001;
        21: atanh_master = 64'h0000_0200_0000_0000;
        22: atanh_master = 64'h0000_0100_0000_0000;
        23: atanh_master = 64'h0000_0080_0000_0000;
        24: atanh_master = 64'h0000_0040_0000_0000;
        25: atanh_master = 64'h0000_0020_0000_0000;
        26: atanh_master = 64'h0000_0010_0000_0000;
        27: atanh_master = 64'h0000_0008_0000_0000;
        28: atanh_master = 64'h0000_0004_0000_0000;
        29: atanh_master = 64'h0000_0002_0000_0000;
        30: atanh_master = 64'h0000_0001_0000_0000;
        31: atanh_master = 64'h0000_0000_8000_0000;
        32: atanh_master = 64'h0000_0000_4000_0000;
        33: atanh_master = 64'h0000_0000_2000_0000;
        34: atanh_master = 64'h0000_0000_1000_0000;
        35: atanh_master = 64'h0000_0000_0800_0000;
        36: atanh_master = 64'h0000_0000_0400_0000;
        37: atanh_master = 64'h0000_0000_0200_0000;
        38: atanh_master = 64'h0000_0000_0100_0000;
        39: atanh_master = 64'h0000_0000_0080_0000;
        40: atanh_master = 64'h0000_0000_0040_0000;
        default: atanh_master = 64'd0;
      endcase
    end
  endfunction
  // END GENERATED

  // ROM over the full address space; entries >= N_ENTRIES are zero
  localparam DEPTH = 1 << ADDR_WIDTH;

  wire signed [PHASE_WIDTH-1:0] lut [0:DEPTH-1];

  genvar j;
  generate
    for (j = 0; j < DEPTH; j = j + 1) begin : g_rom
      if (j < N_ENTRIES) begin : g_entry
        localparam [63:0] MASTER = atanh_master(j + 1);
        localparam [63:0] VALUE  = (MASTER + (64'd1 << (SHIFT - 1))) >> SHIFT;
        assign lut[j] = VALUE[PHASE_WIDTH-1:0];
      end else begin : g_zero
        assign lut[j] = {PHASE_WIDTH{1'b0}};
      end
    end
  endgenerate

  assign data = lut[address];

endmodule
